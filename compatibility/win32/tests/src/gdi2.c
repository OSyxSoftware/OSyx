static BITMAPINFO info(int w, int h, int bpp) {
    BITMAPINFO b = {0}; b.bmiHeader.biSize = sizeof(BITMAPINFOHEADER);
    b.bmiHeader.biWidth = w; b.bmiHeader.biHeight = h;
    b.bmiHeader.biPlanes = 1; b.bmiHeader.biBitCount = (WORD)bpp; return b;
}
static HBITMAP dib(HDC dc, int w, int h, DWORD **bits) {
    BITMAPINFO b = info(w,h,32);
    return CreateDIBSection(dc,&b,DIB_RGB_COLORS,(void **)bits,NULL,0);
}
static void raster(HDC screen) {
    HDC a=CreateCompatibleDC(screen), b=CreateCompatibleDC(NULL);
    check("CreateCompatibleDC display and NULL",a && b);
    DWORD *ap=NULL,*bp=NULL;
    HBITMAP ab=dib(screen,4,-4,&ap), bb=dib(screen,4,4,&bp);
    check("CreateDIBSection top-down and bottom-up exposes pixels",ab && bb && ap && bp);
    if (!ab || !bb) { finish("gdi2"); }
    HGDIOBJ olda=SelectObject(a,ab), oldb=SelectObject(b,bb);
    check("SelectObject memory DC returns stock bitmap",olda && oldb);
    check("GetCurrentObject bitmap",GetCurrentObject(a,OBJ_BITMAP)==ab);
    DIBSECTION ds={0};
    check_eq("GetObjectW DIBSECTION size",GetObjectW(ab,sizeof ds,&ds),sizeof ds);
    check("GetObjectW describes DIB pointer and dimensions",ds.dsBm.bmBits==ap && ds.dsBm.bmWidth==4 && ds.dsBm.bmHeight==4 && ds.dsBm.bmWidthBytes==16 && ds.dsBm.bmBitsPixel==32);
    check("DIBSECTION reports absolute header height",ds.dsBmih.biHeight==4 && ds.dsBmih.biSize==40 && ds.dsBmih.biPlanes==1);
    check_eq("GetObjectW size query",GetObjectW(ab,0,NULL),sizeof(BITMAP));
    check_eq("GetObjectW undersized output fails",GetObjectW(ab,4,&ds),0);
    ap[0]=0x7f112233; ap[1]=0x00abcdef; ap[4]=0x00ff0000;
    GdiFlush();
    check_eq("GetPixel reads direct top-down DIB writes",GetPixel(a,0,0),RGB(0x11,0x22,0x33));
    check_eq("SetPixel on memory DC",SetPixel(a,2,1,RGB(4,5,6)),RGB(4,5,6));
    GdiFlush();
    check_eq("unrelated drawing preserves existing alpha",ap[0],0x7f112233);
    check_eq("SetPixel updates exposed BGRA storage",ap[6]&0xffffff,0x040506);
    check("BitBlt SRCCOPY",BitBlt(b,0,0,4,4,a,0,0,SRCCOPY));
    GdiFlush();
    check_eq("BitBlt preserves all 32 BGRA bits",bp[12],0x7f112233);
    check_eq("BitBlt writes bottom-up storage",bp[12]&0xffffff,0x112233);
    check_eq("BitBlt converts row orientation",GetPixel(b,2,1),RGB(4,5,6));
    check("BitBlt overlapping self copy",BitBlt(a,1,0,3,1,a,0,0,SRCCOPY));
    check_eq("overlap retains original second source pixel",GetPixel(a,2,0),RGB(0xab,0xcd,0xef));
    check("BitBlt BLACKNESS without source",BitBlt(b,0,0,4,4,NULL,0,0,BLACKNESS));
    check_eq("BLACKNESS value",GetPixel(b,2,2),RGB(0,0,0));
    check("BitBlt WHITENESS without source",BitBlt(b,0,0,4,4,NULL,0,0,WHITENESS));
    check_eq("WHITENESS value",GetPixel(b,2,2),RGB(255,255,255));
    check("IntersectClipRect succeeds",IntersectClipRect(b,1,1,3,3)>NULLREGION);
    check("BitBlt respects destination clipping",BitBlt(b,0,0,4,4,NULL,0,0,BLACKNESS));
    check_eq("clipped destination inside",GetPixel(b,1,1),RGB(0,0,0));
    check_eq("GetPixel outside clip fails",GetPixel(b,0,0),CLR_INVALID);
    SelectClipRgn(b,NULL);
    check_eq("clipped destination outside",GetPixel(b,0,0),RGB(255,255,255));
    SelectClipRgn(b,NULL);
    SelectObject(a,olda); SelectObject(b,oldb);
    BITMAPINFO q={0}; q.bmiHeader.biSize=40;
    check("GetDIBits header query",GetDIBits(screen,ab,0,0,NULL,&q,0)!=0);
    check("GetDIBits header fields",q.bmiHeader.biWidth==4 && q.bmiHeader.biBitCount==32 && q.bmiHeader.biPlanes==1);
    BYTE out24[48]={0}; BITMAPINFO i24=info(4,-4,24);
    check_eq("GetDIBits 32 to 24 top-down",GetDIBits(screen,ab,0,4,out24,&i24,0),4);
    check("24-bpp BGR output",out24[0]==0x33 && out24[1]==0x22 && out24[2]==0x11);
    BYTE partial[12]; memset(partial,0x55,sizeof partial);
    check_eq("GetDIBits partial row",GetDIBits(screen,ab,2,1,partial,&i24,0),1);
    check("partial row has correct color",partial[6]==6 && partial[7]==5 && partial[8]==4);
    WORD out16[16]={0}; BITMAPINFO o16=info(4,-4,16);
    check_eq("GetDIBits 32 to RGB555",GetDIBits(screen,ab,0,4,out16,&o16,0),4);
    check_eq("RGB555 output red",out16[4],0x7c00);
    struct { BITMAPINFOHEADER h; RGBQUAD colors[256]; } o8={0};
    o8.h=info(4,-4,8).bmiHeader; BYTE out8[16]={0};
    check_eq("GetDIBits 32 to indexed",GetDIBits(screen,ab,0,4,out8,(BITMAPINFO *)&o8,0),4);
    RGBQUAD red8=o8.colors[out8[4]];
    check("indexed output palette preserves primary red",red8.rgbRed==255 && red8.rgbGreen==0 && red8.rgbBlue==0);
    DWORD row[4]={0x00010203,0x00040506,0x00070809,0x000a0b0c};
    BITMAPINFO ri=info(4,-4,32);
    check_eq("SetDIBits partial top-down row",SetDIBits(screen,bb,1,1,row,&ri,0),1);
    SelectObject(b,bb);
    check_eq("SetDIBits row offset",GetPixel(b,2,2),RGB(7,8,9));
    SelectObject(b,oldb);
    BYTE src24[8]={0,0,255,0,255,0,0,0}; BITMAPINFO s24=info(2,-1,24);
    SelectObject(b,bb);
    check_eq("StretchDIBits padded 24-bpp input",StretchDIBits(b,0,0,4,2,0,0,2,1,src24,&s24,0,SRCCOPY),1);
    check_eq("StretchDIBits nearest red",GetPixel(b,0,0),RGB(255,0,0));
    check_eq("StretchDIBits nearest green",GetPixel(b,3,1),RGB(0,255,0));
    WORD src16[2]={0x7c00,0x001f}; BITMAPINFO s16=info(2,-1,16);
    check_eq("StretchDIBits RGB555 input",StretchDIBits(b,0,2,2,1,0,0,2,1,src16,&s16,0,SRCCOPY),1);
    check_eq("RGB555 red",GetPixel(b,0,2),RGB(255,0,0));
    check_eq("RGB555 blue",GetPixel(b,1,2),RGB(0,0,255));
    struct { BITMAPINFOHEADER h; RGBQUAD colors[256]; } indexed={0};
    indexed.h=info(2,-1,8).bmiHeader; indexed.colors[1].rgbRed=255; indexed.colors[2].rgbBlue=255;
    BYTE src8[4]={1,2,0,0};
    check_eq("StretchDIBits indexed 8-bpp",StretchDIBits(b,0,3,2,1,0,0,2,1,src8,(BITMAPINFO *)&indexed,0,SRCCOPY),1);
    check_eq("8-bpp palette red",GetPixel(b,0,3),RGB(255,0,0));
    check_eq("8-bpp palette blue",GetPixel(b,1,3),RGB(0,0,255));
    SelectObject(b,oldb);
    HBITMAP compat=CreateCompatibleBitmap(screen,3,2);
    BITMAP bm={0};
    check("CreateCompatibleBitmap display",compat!=NULL);
    check("compatible bitmap descriptor",GetObjectW(compat,sizeof bm,&bm)==sizeof bm && bm.bmWidth==3 && bm.bmHeight==2 && bm.bmBitsPixel>=24);
    WORD mono[2]={0x0080,0x0040}; HBITMAP raw=CreateBitmap(2,2,1,1,mono);
    check("CreateBitmap monochrome",raw!=NULL);
    check("CreateBitmap descriptor",GetObjectW(raw,sizeof bm,&bm)==sizeof bm && bm.bmBitsPixel==1 && bm.bmWidth==2);
    HBITMAP from=CreateDIBitmap(screen,&s24.bmiHeader,CBM_INIT,src24,&s24,0);
    check("CreateDIBitmap CBM_INIT",from!=NULL);
    SelectObject(b,from); check_eq("CreateDIBitmap initial pixels",GetPixel(b,0,0),RGB(255,0,0)); SelectObject(b,oldb);
    check("DeleteObject bitmap resources",DeleteObject(from) && DeleteObject(raw) && DeleteObject(compat) && DeleteObject(ab) && DeleteObject(bb));
    check("DeleteDC memory resources",DeleteDC(a) && DeleteDC(b));
    check("DeleteDC invalid handle fails",!DeleteDC(NULL));
}

static void regions_paths(HDC dc) {
    HRGN r=CreateRectRgn(1,1,7,7), copy=CreateRectRgn(0,0,0,0), hole=CreateRectRgn(3,3,5,5);
    check("CreateRectRgn",r && copy && hole);
    RECT box={0}; check_eq("GetRgnBox simple",GetRgnBox(r,&box),SIMPLEREGION);
    check("GetRgnBox edges",box.left==1 && box.top==1 && box.right==7 && box.bottom==7);
    check_eq("GetRegionData size query",GetRegionData(r,0,NULL),48);
    struct { RGNDATAHEADER h; RECT rects[16]; } data={0};
    check_eq("GetRegionData output size",GetRegionData(r,sizeof data,(RGNDATA *)&data),48);
    check("RGNDATA header and rectangle",data.h.dwSize==32 && data.h.iType==RDH_RECTANGLES && data.h.nCount==1 && data.h.nRgnSize==16 && data.rects[0].left==1);
    XFORM shift={1,0,0,1,2,1}; HRGN transformed=ExtCreateRegion(&shift,48,(RGNDATA *)&data);
    check("ExtCreateRegion transform",transformed!=NULL);
    GetRgnBox(transformed,&box); check("region transformed bounds",box.left==3 && box.top==2 && box.right==9);
    check_eq("OffsetRgn",OffsetRgn(transformed,-2,-1),SIMPLEREGION);
    check_eq("SelectClipRgn",SelectClipRgn(dc,r),SIMPLEREGION);
    check_eq("GetClipRgn copies selected region",GetClipRgn(dc,copy),1);
    GetRgnBox(copy,&box); check_eq("copied clip left",box.left,1);
    check_eq("ExtSelectClipRgn subtracts hole",ExtSelectClipRgn(dc,hole,RGN_DIFF),COMPLEXREGION);
    check_eq("SetPixel succeeds in first rectangle of complex clip",SetPixel(dc,1,1,RGB(1,2,3)),RGB(1,2,3));
    check_eq("SetPixel rejects region hole",SetPixel(dc,4,4,RGB(1,2,3)),CLR_INVALID);
    check("region-clipped WHITENESS",BitBlt(dc,0,0,8,8,NULL,0,0,WHITENESS));
    check_eq("region draws outer part",GetPixel(dc,2,2),RGB(255,255,255));
    check_eq("GetClipBox complex",GetClipBox(dc,&box),COMPLEXREGION);
    SelectClipRgn(dc,NULL);
    check_eq("region preserves hole",GetPixel(dc,4,4),RGB(0,0,0));
    check_eq("region preserves outside",GetPixel(dc,0,0),RGB(0,0,0));
    check("GetRandomRgn SYSRGN",GetRandomRgn(dc,copy,4)==1);
    SelectClipRgn(dc,NULL); check_eq("GetClipRgn absent",GetClipRgn(dc,copy),0);
    check("BeginPath rectangle",BeginPath(dc));
    check("Rectangle records path",Rectangle(dc,1,1,4,4));
    check("EndPath rectangle",EndPath(dc));
    HBRUSH red=CreateSolidBrush(RGB(255,0,0)); HGDIOBJ old=SelectObject(dc,red);
    check("FillPath",FillPath(dc)); check_eq("filled path pixel",GetPixel(dc,2,2),RGB(255,0,0));
    SelectObject(dc,old); DeleteObject(red);
    check("BeginPath polygon",BeginPath(dc)); MoveToEx(dc,5,1,NULL); LineTo(dc,7,1); LineTo(dc,7,3);
    check("CloseFigure",CloseFigure(dc)); EndPath(dc);
    check("SelectClipPath",SelectClipPath(dc,RGN_COPY));
    check("GetClipRgn after path",GetClipRgn(dc,copy)==1); SelectClipRgn(dc,NULL);
    LOGBRUSH lb={BS_SOLID,RGB(0,255,0),0}; HPEN pen=ExtCreatePen(PS_GEOMETRIC|PS_SOLID,1,&lb,0,NULL);
    check("ExtCreatePen solid",pen!=NULL); old=SelectObject(dc,pen);
    BeginPath(dc); MoveToEx(dc,1,6,NULL); LineTo(dc,6,6); EndPath(dc);
    check("StrokePath",StrokePath(dc)); check_eq("stroke pixel",GetPixel(dc,3,6),RGB(0,255,0));
    BeginPath(dc); MoveToEx(dc,0,7,NULL); POINT points[3]={{2,7},{4,7},{6,7}};
    check("PolyBezierTo records cubic",PolyBezierTo(dc,points,3)); EndPath(dc); check("StrokePath cubic",StrokePath(dc));
    check_eq("Bezier stroke pixel",GetPixel(dc,3,7),RGB(0,255,0));
    check("WidenPath invalid DC fails",!WidenPath(NULL));
    BeginPath(dc); MoveToEx(dc,1,4,NULL); LineTo(dc,6,4); EndPath(dc);
    check("WidenPath completed stroke",WidenPath(dc)); check("FillPath widened stroke",FillPath(dc));
    SelectObject(dc,old); DeleteObject(pen);
    check("region cleanup",DeleteObject(r) && DeleteObject(copy) && DeleteObject(hole) && DeleteObject(transformed));
}

static void state_text(HDC dc) {
    check_eq("SaveDC first level",SaveDC(dc),1);
    SetBkColor(dc,RGB(1,2,3)); SetTextColor(dc,RGB(4,5,6));
    check_eq("SetTextAlign initial",SetTextAlign(dc,TA_CENTER|TA_BASELINE),TA_LEFT|TA_TOP);
    check_eq("SetTextAlign keeps value",SetTextAlign(dc,TA_RIGHT|TA_BOTTOM),TA_CENTER|TA_BASELINE);
    check_eq("SetGraphicsMode returns compatible",SetGraphicsMode(dc,GM_ADVANCED),GM_COMPATIBLE);
    XFORM x={1,0,0,1,2,3},got={0};
    check("SetWorldTransform",SetWorldTransform(dc,&x)); check("GetWorldTransform",GetWorldTransform(dc,&got));
    check("world transform round-trip",mem_eq(&x,&got,sizeof x));
    check("SetPixel transforms position",SetPixel(dc,0,0,RGB(12,13,14))==RGB(12,13,14));
    XFORM scale={2,0,0,2,0,0}; check("ModifyWorldTransform left",ModifyWorldTransform(dc,&scale,MWT_LEFTMULTIPLY));
    GetWorldTransform(dc,&got); check("left multiplication order",got.eM11==2 && got.eDx==2 && got.eDy==3);
    check("ModifyWorldTransform right",ModifyWorldTransform(dc,&x,MWT_RIGHTMULTIPLY));
    GetWorldTransform(dc,&got); check("right multiplication order",got.eDx==4 && got.eDy==6);
    check("ModifyWorldTransform identity NULL",ModifyWorldTransform(dc,NULL,MWT_IDENTITY));
    check_eq("GetGraphicsMode advanced",GetGraphicsMode(dc),GM_ADVANCED);
    FLOAT old=0; check("SetMiterLimit XMM argument",SetMiterLimit(dc,7.5f,&old) && old==10.0f);
    check("SetMiterLimit keeps state",SetMiterLimit(dc,8.0f,&old) && old==7.5f);
    check_eq("SetMapMode MM_TEXT",SetMapMode(dc,MM_TEXT),MM_TEXT);
    check_eq("SetPolyFillMode",SetPolyFillMode(dc,WINDING),ALTERNATE);
    check_eq("SetStretchBltMode",SetStretchBltMode(dc,COLORONCOLOR),BLACKONWHITE);
    check_eq("SaveDC nested level",SaveDC(dc),2); SelectClipRgn(dc,NULL); IntersectClipRect(dc,0,0,1,1);
    check("RestoreDC negative level",RestoreDC(dc,-1));
    check("RestoreDC absolute level",RestoreDC(dc,1));
    check_eq("RestoreDC restores text alignment",SetTextAlign(dc,0),0);
    check_eq("RestoreDC restores background color",SetBkColor(dc,RGB(255,0,0)),RGB(255,255,255));
    check("RestoreDC invalid level",!RestoreDC(dc,-1));
    RECT r={0,0,2,2};
    check("ExtTextOutW opaque without text",ExtTextOutW(dc,0,0,ETO_OPAQUE,&r,NULL,0,NULL));
    check_eq("ExtTextOutW opaque pixel",GetPixel(dc,1,1),RGB(255,0,0));
    SetBkMode(dc,TRANSPARENT); SetTextColor(dc,RGB(255,255,255));
    int dx[2]={5,7}; RECT clip={0,0,8,8};
    check("ExtTextOutW clipped advances",ExtTextOutW(dc,0,0,ETO_CLIPPED,&clip,L"AB",2,dx));
    SetTextAlign(dc,TA_UPDATECP); MoveToEx(dc,1,1,NULL);
    check("ExtTextOutW TA_UPDATECP",ExtTextOutW(dc,99,99,0,NULL,L"AB",2,dx));
    POINT pos; MoveToEx(dc,0,0,&pos); check_eq("text advances current position",pos.x,13); SetTextAlign(dc,0);
    int widths[3]={0}; check("GetCharWidth32A",GetCharWidth32A(dc,'A','C',widths) && widths[0]>0 && widths[1]>0);
    check("GetCharWidth32A rejects reversed range",!GetCharWidth32A(dc,'C','A',widths));
    DWORD font_size=GetFontData(dc,0,0,NULL,0);
    check("GetFontData rejects missing table",GetFontData(dc,0x5a5a5a5a,0,NULL,0)==GDI_ERROR);
    check("GetFontData query is available or bitmap font",font_size==GDI_ERROR || font_size>0);
    DWORD ranges=GetFontUnicodeRanges(dc,NULL);
    check("GetFontUnicodeRanges size",ranges>=sizeof(GLYPHSET));
    GLYPHSET *gs=HeapAlloc(GetProcessHeap(),HEAP_ZERO_MEMORY,ranges);
    check("GetFontUnicodeRanges output",gs && GetFontUnicodeRanges(dc,gs)==ranges && gs->cbThis==ranges && gs->cRanges>0 && gs->cGlyphsSupported>0);
    if (gs) HeapFree(GetProcessHeap(),0,gs);
    WORD indices[3]={0}; check_eq("GetGlyphIndicesW count",GetGlyphIndicesW(dc,L"AB\xffff",3,indices,GGI_MARK_NONEXISTING_GLYPHS),3);
    check("GetGlyphIndicesW supported and missing",indices[0]!=0xffff && indices[1]!=0xffff && indices[2]==0xffff);
    check("ExtTextOutW glyph indices",ExtTextOutW(dc,0,0,ETO_GLYPH_INDEX,NULL,(WCHAR *)indices,2,NULL));
    MAT2 mat={ {0,1},{0,0},{0,0},{0,1} }; GLYPHMETRICS gm={0};
    HFONT font=CreateFontW(-14,0,0,0,FW_NORMAL,0,0,0,DEFAULT_CHARSET,0,0,0,0,L"Arial");
    HGDIOBJ previous=SelectObject(dc,font);
    DWORD glyph=GetGlyphOutlineW(dc,'A',GGO_METRICS,&gm,0,NULL,&mat);
    check("GetGlyphOutlineW metrics or bitmap font rejection",glyph==GDI_ERROR || gm.gmCellIncX>0);
    if (glyph!=GDI_ERROR) {
        BYTE output[4096]; DWORD need=GetGlyphOutlineW(dc,'A',GGO_BITMAP,&gm,0,NULL,&mat);
        check("GetGlyphOutlineW bitmap query",need!=GDI_ERROR && need<=sizeof output);
        check_eq("GetGlyphOutlineW bitmap output",GetGlyphOutlineW(dc,'A',GGO_BITMAP,&gm,sizeof output,output,&mat),need);
    } else { check("GetGlyphOutlineW bitmap font branch",1); check("GetGlyphOutlineW bitmap font branch output",1); }
    SelectObject(dc,previous); DeleteObject(font);
    DWORD outline=GetOutlineTextMetricsA(dc,0,NULL);
    check("GetOutlineTextMetricsA query or bitmap font",outline==0 || outline>=sizeof(OUTLINETEXTMETRICA));
    check("GetICMProfileW invalid DC",!GetICMProfileW(NULL,&ranges,NULL));
    PIXELFORMATDESCRIPTOR pfd={0}; pfd.nSize=sizeof pfd; pfd.nVersion=1;
    check_eq("ChoosePixelFormat invalid DC",ChoosePixelFormat(NULL,&pfd),0);
    check("SetPixelFormat invalid DC",!SetPixelFormat(NULL,1,&pfd));
    check("SwapBuffers invalid DC",!SwapBuffers(NULL));
    check_eq("ExtEscape unsupported query",ExtEscape(dc,0x7fffffff,0,NULL,0,NULL),0);
    BitBlt(dc,0,0,8,8,NULL,0,0,BLACKNESS);
    HGDIOBJ saved_font=SelectObject(dc,GetStockObject(ANSI_FIXED_FONT));
    RECT tiny={0,0,2,2};
    check("ExtTextOutW clips monochrome font",ExtTextOutW(dc,0,0,ETO_CLIPPED,&tiny,L"W",1,NULL));
    check_eq("monochrome glyph preserves pixel outside ETO clip",GetPixel(dc,3,4),RGB(0,0,0));
    SelectObject(dc,saved_font);
}

void __stdcall start(void) {
    HDC window_screen = GetWindowDC(NULL);
    check("GetWindowDC desktop", window_screen != NULL && GetDeviceCaps(window_screen, BITSPIXEL) > 0);
    check("ReleaseDC desktop window context", ReleaseDC(NULL, window_screen) == 1);
    HDC screen=CreateDCW(L"DISPLAY",NULL,NULL,NULL);
    check("CreateDCW DISPLAY",screen!=NULL);
    HDC ansi=CreateDCA("DISPLAY",NULL,NULL,NULL), ic=CreateICW(L"DISPLAY",NULL,NULL,NULL);
    check("CreateDCA DISPLAY",ansi!=NULL); check("CreateICW DISPLAY",ic!=NULL);
    /* CreateDC is a header alias on Windows, rather than a required DLL export. */
    HDC alias=CreateDC("DISPLAY",NULL,NULL,NULL);
    check("CreateDC alias",alias!=NULL); DeleteDC(alias);
    check_eq("display depth",GetDeviceCaps(screen,BITSPIXEL),32);
    raster(screen);
    HDC dc=CreateCompatibleDC(screen); DWORD *bits=NULL; HBITMAP bitmap=dib(screen,8,-8,&bits);
    check("path fixture DIB",dc && bitmap && bits); HGDIOBJ old=SelectObject(dc,bitmap);
    regions_paths(dc); state_text(dc);
    SelectObject(dc,old); DeleteObject(bitmap); DeleteDC(dc);
    check("DeleteDC display and information",DeleteDC(screen) && DeleteDC(ansi) && DeleteDC(ic));
    finish("gdi2");
}
