//! The tables were read from Windows' own US layout (MapVirtualKeyEx and
//! ToUnicodeEx on Windows 10.0.26300) for every virtual key.

/// No character for that modifier state.
pub const NONE: u16 = 0xFFFF;

/// A virtual key: its scan code (0xE0nn for extended keys), its
/// MAPVK_VK_TO_CHAR value, and its character with no modifiers, Shift,
/// Ctrl, Ctrl+Shift, Caps Lock and Caps Lock+Shift.
