//! Bridge signatures of the built-in functions 32-bit programs may import.
//! Each 32-bit stack slot of a stdcall function becomes one Win64 argument
//! (see `ArgKind`). Derived from the Win64 host declarations: pointers
//! stay pointers (the runtime's memory is below 2 GiB for 32-bit
//! programs), 32-bit values keep their sign, handles are
//! sign-extended, and `*mut` 64-bit outputs (HKEY, HANDLE, PIDL,
//! DWORD_PTR) go through a 64-bit temporary (`OutWide`).
//!
//! Not listed on purpose, so a program importing them fails to load with
//! the name: functions whose structures differ between 32 and 64 bits
//! (MSG, PAINTSTRUCT, WNDCLASSW, SHFILEINFOW, BROWSEINFOW),
//! that call back into 32-bit code (window and thread procedures), that
//! return 64-bit code addresses (GetProcAddress) or load modules
//! (LoadLibraryExW), and variadic ones (wsprintf). CreateThread is listed:
//! its 32-bit start routine runs through `wow64::CreateThread32`.

use super::{ArgKind, RetKind, Signature};

macro_rules! sig {
    ($name:ident, [$($a:ident),*], $r:ident) => {
        Signature { name: stringify!($name), args: &[$(ArgKind::$a),*], ret: RetKind::$r, is_cdecl: false }
    };
}

