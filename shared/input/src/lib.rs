//! OSyx input events.
//!
//! The kernel input core turns device reports (USB HID today) into a single
//! stream of [`InputEvent`]s, readable from `/dev/input/event<N>` (one
//! device) and `/dev/input/seat0` (all devices, held by the graphical
//! session). Events are raw: a key event names a physical key (its HID
//! Keyboard/Keypad usage id, see [`key`]); which character it produces is
//! decided later by a [`layout`], so text input stays separate from key
//! events.
//!
//! Every event is exactly [`InputEvent::SIZE`] bytes, little-endian, with
//! no padding (see [`InputEvent::encode`]).

#![no_std]

pub mod key;
pub mod layout;
pub mod repeat;

/// Event kinds.
pub mod kind {
    /// `code` = key (HID usage), `value` = [`super::KEY_UP`] / `KEY_DOWN` / `KEY_REPEAT`.
    pub const KEY: u16 = 1;
    /// Relative pointer motion: `value` = dx, `value2` = dy (screen
    /// orientation: +x right, +y down).
    pub const MOTION: u16 = 2;
    /// `code` = button ([`super::button`]), `value` = 1 pressed / 0 released.
    pub const BUTTON: u16 = 3;
    /// Scrolling: `value` = vertical detents (+ = away from the user),
    /// `value2` = horizontal (+ = right).
    pub const WHEEL: u16 = 4;
    /// `code` = [`super::DEVICE_ADDED`] / [`super::DEVICE_REMOVED`],
    /// `value` = device class ([`super::class`]).
    pub const DEVICE: u16 = 5;
    /// The reader fell behind and `value` events were dropped before this one.
    pub const DROPPED: u16 = 6;
}

pub const KEY_UP: i32 = 0;
pub const KEY_DOWN: i32 = 1;
/// Generated by the input core while a key stays down.
pub const KEY_REPEAT: i32 = 2;

pub const DEVICE_ADDED: u16 = 1;
pub const DEVICE_REMOVED: u16 = 2;

/// Device classes.
pub mod class {
    pub const KEYBOARD: i32 = 1;
    pub const MOUSE: i32 = 2;
}

/// Pointer buttons.
pub mod button {
    pub const LEFT: u16 = 1;
    pub const RIGHT: u16 = 2;
    pub const MIDDLE: u16 = 3;
    pub const BACK: u16 = 4;
    pub const FORWARD: u16 = 5;
}

/// Modifier and lock state carried by every event (the state after the
/// event). The low byte matches the HID boot keyboard modifier byte.
pub mod modifier {
    pub const LEFT_CTRL: u32 = 1 << 0;
    pub const LEFT_SHIFT: u32 = 1 << 1;
    pub const LEFT_ALT: u32 = 1 << 2;
    pub const LEFT_GUI: u32 = 1 << 3;
    pub const RIGHT_CTRL: u32 = 1 << 4;
    pub const RIGHT_SHIFT: u32 = 1 << 5;
    /// AltGr on most European layouts.
    pub const RIGHT_ALT: u32 = 1 << 6;
    pub const RIGHT_GUI: u32 = 1 << 7;
    pub const CAPS_LOCK: u32 = 1 << 8;
    pub const NUM_LOCK: u32 = 1 << 9;
    pub const SCROLL_LOCK: u32 = 1 << 10;

    pub const CTRL: u32 = LEFT_CTRL | RIGHT_CTRL;
    pub const SHIFT: u32 = LEFT_SHIFT | RIGHT_SHIFT;
    pub const ALT: u32 = LEFT_ALT | RIGHT_ALT;
    pub const GUI: u32 = LEFT_GUI | RIGHT_GUI;
}

/// One input event.
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
pub struct InputEvent {
    /// Monotonic time in nanoseconds since boot.
    pub time_ns: u64,
    /// Input core device id (stable while the device is attached).
    pub device: u32,
    pub kind: u16,
    pub code: u16,
    pub value: i32,
    pub value2: i32,
    /// [`modifier`] bits after this event.
    pub modifiers: u32,
    /// Per-stream sequence number (gaps mean dropped events).
    pub seq: u32,
}

impl InputEvent {
    pub const SIZE: usize = 32;

    pub fn encode(&self) -> [u8; Self::SIZE] {
        let mut b = [0u8; Self::SIZE];
        b[0..8].copy_from_slice(&self.time_ns.to_le_bytes());
        b[8..12].copy_from_slice(&self.device.to_le_bytes());
        b[12..14].copy_from_slice(&self.kind.to_le_bytes());
        b[14..16].copy_from_slice(&self.code.to_le_bytes());
        b[16..20].copy_from_slice(&self.value.to_le_bytes());
        b[20..24].copy_from_slice(&self.value2.to_le_bytes());
        b[24..28].copy_from_slice(&self.modifiers.to_le_bytes());
        b[28..32].copy_from_slice(&self.seq.to_le_bytes());
        b
    }

    pub fn decode(b: &[u8]) -> Option<InputEvent> {
        let b: &[u8; Self::SIZE] = b.get(..Self::SIZE)?.try_into().ok()?;
        let u32_at = |o: usize| u32::from_le_bytes([b[o], b[o + 1], b[o + 2], b[o + 3]]);
        Some(InputEvent {
            time_ns: u64::from_le_bytes(b[0..8].try_into().ok()?),
            device: u32_at(8),
            kind: u16::from_le_bytes([b[12], b[13]]),
            code: u16::from_le_bytes([b[14], b[15]]),
            value: u32_at(16) as i32,
            value2: u32_at(20) as i32,
            modifiers: u32_at(24),
            seq: u32_at(28),
        })
    }

    pub fn is_key(&self) -> bool {
        self.kind == kind::KEY
    }

    pub fn is_press(&self) -> bool {
        self.kind == kind::KEY && (self.value == KEY_DOWN || self.value == KEY_REPEAT)
    }
}

/// Tracks modifier and lock state from key events (the input core keeps
/// one per seat; lock keys toggle on press).
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
pub struct ModifierState {
    bits: u32,
}

impl ModifierState {
    pub fn bits(&self) -> u32 {
        self.bits
    }

    /// Applies a key press (`down`) or release; returns true if a lock state
    /// changed (keyboard LEDs need an update).
    pub fn apply(&mut self, usage: u16, down: bool) -> bool {
        if let Some(bit) = key::modifier_bit(usage) {
            if down {
                self.bits |= bit;
            } else {
                self.bits &= !bit;
            }
            return false;
        }
        let lock = match usage {
            key::CAPS_LOCK => modifier::CAPS_LOCK,
            key::NUM_LOCK => modifier::NUM_LOCK,
            key::SCROLL_LOCK => modifier::SCROLL_LOCK,
            _ => return false,
        };
        if down {
            self.bits ^= lock;
            return true;
        }
        false
    }

    /// Clears held modifiers (all keyboards gone); locks are kept.
    pub fn release_held(&mut self) {
        self.bits &= modifier::CAPS_LOCK | modifier::NUM_LOCK | modifier::SCROLL_LOCK;
    }

    /// HID LED output report byte for the lock state.
    pub fn leds(&self) -> u8 {
        u8::from(self.bits & modifier::NUM_LOCK != 0)
            | u8::from(self.bits & modifier::CAPS_LOCK != 0) << 1
            | u8::from(self.bits & modifier::SCROLL_LOCK != 0) << 2
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn event_round_trip() {
        let e = InputEvent {
            time_ns: 0x0102_0304_0506_0708,
            device: 3,
            kind: kind::MOTION,
            code: 0,
            value: -5,
            value2: 7,
            modifiers: modifier::LEFT_SHIFT | modifier::CAPS_LOCK,
            seq: 99,
        };
        let b = e.encode();
        assert_eq!(b.len(), 32);
        assert_eq!(InputEvent::decode(&b), Some(e));
        assert_eq!(InputEvent::decode(&b[..31]), None);
        assert_eq!(&b[12..14], &[2, 0]);
    }

    #[test]
    fn modifier_and_lock_tracking() {
        let mut m = ModifierState::default();
        assert!(!m.apply(key::LEFT_SHIFT, true));
        assert_eq!(m.bits(), modifier::LEFT_SHIFT);
        assert!(m.apply(key::CAPS_LOCK, true), "caps lock toggles on press");
        assert!(!m.apply(key::CAPS_LOCK, false));
        assert_eq!(m.bits(), modifier::LEFT_SHIFT | modifier::CAPS_LOCK);
        assert_eq!(m.leds(), 0b010);
        m.apply(key::NUM_LOCK, true);
        assert_eq!(m.leds(), 0b011);
        m.apply(key::CAPS_LOCK, true);
        assert_eq!(m.leds(), 0b001);
        m.apply(key::LEFT_SHIFT, false);
        m.apply(key::RIGHT_ALT, true);
        m.release_held();
        assert_eq!(m.bits(), modifier::NUM_LOCK);
        assert!(!m.apply(key::A, true));
    }
}
